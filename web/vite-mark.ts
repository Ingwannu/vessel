// The owner's mark on the page (docs/design/brand/, 2026-11-13), made by
// the build from the one source every client draws it from:
//
// - `virtual:vessel-mark`: the mark's view box and paths, which the
//   sidebar's head draws in the text's colour at the text's size (the
//   brand's README: "in the interface, the mono file at the size of the
//   text beside it");
// - `favicon.svg`: the mark in white on a tile of the brand colour,
//   rounded (the README's rule for icons: on white the nested lines turn
//   pale at 32 px and below, on the tile they still read), linked from
//   the index.
//
// [Decision Log]
// - Purpose: the page showed a drawn placeholder, and no favicon.
// - Constraint: the brand's README keeps generated icons out of the
//   repository ("generated by each client's build"); the page draws no
//   markup from a string (no innerHTML), and its index allows images
//   from itself only (CSP `img-src 'self'`).
// - Alternatives: copy the paths into a component (a second copy that
//   drifts from the owner's file); load the SVG as an image or a CSS mask
//   (a request per launch, and a mask's colour follows the theme only
//   through CSS the kit does not have).
// - Choice: read the paths at build time, hand them to React as data,
//   and write the favicon as a build asset.
// - Cost: the build reads a file outside `web/`; a mark whose file
//   changes shape (more than paths) is refused here, loudly.

import { readFileSync } from "node:fs";
import { join } from "node:path";

import type { Plugin } from "vite";

const SOURCE = join(
  import.meta.dirname,
  "..",
  "docs",
  "design",
  "brand",
  "vessel-mark.svg",
);
const MODULE = "virtual:vessel-mark";
const RESOLVED = `\0${MODULE}`;
/** The brand colour (docs/design/brand/README.md). */
const BRAND = "#1a5868";

interface Mark {
  viewBox: string;
  paths: { d: string; evenOdd: boolean }[];
}

function readMark(): Mark {
  const text = readFileSync(SOURCE, "utf8");
  const viewBox = /viewBox="([^"]+)"/.exec(text)?.[1];
  const paths = [...text.matchAll(/<path\b([^>]*)\/?>/g)].map((match) => {
    const attributes = match[1] ?? "";
    const d = /\sd="([^"]+)"/.exec(attributes)?.[1];
    if (d === undefined) {
      throw new Error("the mark has a path without data");
    }
    return { d, evenOdd: attributes.includes('fill-rule="evenodd"') };
  });
  if (viewBox === undefined || paths.length === 0) {
    throw new Error("the mark is not a view box and paths any more");
  }
  return { viewBox, paths };
}

/** The favicon's states beside the plain one (ADR 0089, "The page's badge
 * and favicon"): Paseo's running and attention favicons add one dot at the
 * bottom right, at
 * cx = cy = 570 and r = 130 of a 700 side, blue while anything runs and
 * green when something wants the person (`favicon-dark-running.svg`,
 * `favicon-dark-attention.svg`). The same ratio on the 64 tile. */
const STATES = { running: "#3b82f6", attention: "#22c55e" } as const;

/** The favicon: the mark in white on a rounded tile of the brand colour,
 * with the room a launcher's icon gives it, and a state's dot when given. */
function favicon(mark: Mark, dot?: string): string {
  const paths = mark.paths
    .map(
      (path) =>
        `<path fill="#fff"${path.evenOdd ? ' fill-rule="evenodd"' : ""} d="${path.d}"/>`,
    )
    .join("");
  const state =
    dot === undefined
      ? ""
      : `<circle cx="52.11" cy="52.11" r="11.89" fill="${dot}"/>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="14" fill="${BRAND}"/><svg x="10" y="10" width="44" height="44" viewBox="${mark.viewBox}">${paths}</svg>${state}</svg>`;
}

export function vesselMark(): Plugin {
  return {
    name: "vessel-mark",
    resolveId(id) {
      return id === MODULE ? RESOLVED : null;
    },
    load(id) {
      if (id !== RESOLVED) {
        return null;
      }
      this.addWatchFile(SOURCE);
      return `export const mark = ${JSON.stringify(readMark())};`;
    },
    generateBundle() {
      const read = readMark();
      this.emitFile({
        type: "asset",
        fileName: "favicon.svg",
        source: favicon(read),
      });
      for (const [state, colour] of Object.entries(STATES)) {
        this.emitFile({
          type: "asset",
          fileName: `favicon-${state}.svg`,
          source: favicon(read, colour),
        });
      }
    },
    transformIndexHtml() {
      return [
        {
          tag: "link",
          attrs: { rel: "icon", type: "image/svg+xml", href: "/favicon.svg" },
          injectTo: "head",
        },
      ];
    },
  };
}
