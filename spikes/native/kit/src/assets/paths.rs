//! Exhaustive asset-name data, separate from the inventory and SVG geometry.
//! A declarative table avoids growing a hand-written function for each additive
//! glyph while retaining a compile-time exhaustive match and constant paths.
use super::Glyph;

macro_rules! glyph_paths {
    ($($glyph:ident => $name:literal),+ $(,)?) => {
        impl Glyph {
            /// Its asset path.
            #[must_use]
            pub const fn path(self) -> &'static str {
                match self { $(Self::$glyph => concat!("kit/", $name, ".svg")),+ }
            }
        }
    };
}

