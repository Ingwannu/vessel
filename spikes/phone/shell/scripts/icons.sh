#!/usr/bin/env bash
# Generates the app's icons from the mark, at build time (nothing generated
# is committed; `docs/design/brand/README.md`):
#
#   icons.sh <vessel-mark-mono.svg> <app-dir>
#
# - Android's adaptive launcher icon: the mark in white as the foreground,
#   sized by its width (the mark is wider than tall) to sit inside the
#   launcher's 66 dp safe zone of the 108 dp canvas; the brand colour as
#   the background; the same white mark as the monochrome layer themed
#   icons tint.
# - The legacy launcher icons (before Android 8): the mark in white on a
#   rounded tile, and on a circle, of the brand colour.
# - Tauri's own icon files the desktop build of the shell embeds.
#
# Needs ImageMagick (`convert`) with an SVG reader.
set -euo pipefail

mark=${1:?the mono mark, vessel-mark-mono.svg}
app=${2:?the app crate directory}
brand='#1a5868'
res="$app/gen/android/app/src/main/res"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# The mono mark in white. Its view box is square with about 5% of air on
# the wide side, so the artwork's width is about 0.9 of the box.
sed 's/currentColor/#FFFFFF/g' "$mark" > "$work/white.svg"

# The white mark, its box `box` px square, centred on a transparent
# `canvas` px square.
white() {
  local box=$1 canvas=$2 out=$3
  # Rasterised at twice the size it is drawn (the view box is 1660 units
  # wide at 72 dpi), then scaled down: crisp edges, bounded memory.
  local density=$(( (72 * box * 2 + 1659) / 1660 ))
  convert -background none -density "$density" "$work/white.svg" -resize "${box}x${box}" \
    -gravity center -extent "${canvas}x${canvas}" -depth 8 -define png:color-type=6 "$out"
}

# density name, px per dp (as a fraction of 4: mdpi 4/4 … xxxhdpi 16/4).
densities="mdpi:4 hdpi:6 xhdpi:8 xxhdpi:12 xxxhdpi:16"
for entry in $densities; do
  name=${entry%%:*}; quarter=${entry##*:}
  dir="$res/mipmap-$name"
  mkdir -p "$dir"
  rm -f "$dir"/ic_launcher*.png
  # Adaptive layers: 108 dp canvas; the mark's box 58 dp, so its width
  # (about 52 dp) and height stay inside the 66 dp safe circle.
  canvas=$((108 * quarter / 4)); box=$((58 * quarter / 4))
  white "$box" "$canvas" "$dir/ic_launcher_foreground.png"
  cp "$dir/ic_launcher_foreground.png" "$dir/ic_launcher_monochrome.png"
  # Legacy: 48 dp, the mark's box 32 dp.
  legacy=$((48 * quarter / 4)); lbox=$((32 * quarter / 4)); radius=$((legacy / 5))
  white "$lbox" "$legacy" "$work/mark.png"
  convert -size "${legacy}x${legacy}" xc:none -fill "$brand" \
    -draw "roundrectangle 0,0,$((legacy - 1)),$((legacy - 1)),$radius,$radius" \
    "$work/mark.png" -composite -depth 8 "$dir/ic_launcher.png"
  convert -size "${legacy}x${legacy}" xc:none -fill "$brand" \
    -draw "circle $((legacy / 2)),$((legacy / 2)) $((legacy / 2)),0" \
    "$work/mark.png" -composite -depth 8 "$dir/ic_launcher_round.png"
done

mkdir -p "$res/mipmap-anydpi-v26" "$res/values"
for name in ic_launcher ic_launcher_round; do
  cat > "$res/mipmap-anydpi-v26/$name.xml" <<XML
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/icons.sh from the mark; not committed. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />
</adaptive-icon>
XML
done
cat > "$res/values/ic_launcher_background.xml" <<XML
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/icons.sh: the brand colour. -->
<resources>
    <color name="ic_launcher_background">$brand</color>
</resources>
XML

# Tauri's icon files (the shell's desktop build embeds icons/icon.png as
# its window icon): the mark on the brand tile.
mkdir -p "$app/icons"
for size in 32 128 256 512; do
  box=$((size * 2 / 3)); radius=$((size / 5))
  white "$box" "$size" "$work/mark.png"
  convert -size "${size}x${size}" xc:none -fill "$brand" \
    -draw "roundrectangle 0,0,$((size - 1)),$((size - 1)),$radius,$radius" \
    "$work/mark.png" -composite -depth 8 -define png:color-type=6 "$work/tile-$size.png"
done
cp "$work/tile-32.png" "$app/icons/32x32.png"
cp "$work/tile-128.png" "$app/icons/128x128.png"
cp "$work/tile-256.png" "$app/icons/128x128@2x.png"
cp "$work/tile-512.png" "$app/icons/icon.png"
echo "icons written from $(basename "$mark")"
